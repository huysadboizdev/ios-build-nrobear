    public static string[] Candidates(string root, string path, int zoom)
    {
        root = root.TrimEnd('/');
        path = "/" + path.Replace('\\', '/').TrimStart('/');
        if (path.EndsWith(".png", StringComparison.OrdinalIgnoreCase)) path = path.Substring(0, path.Length - 4);
        string native = root + "/x" + zoom + path;
        string original = root + path;
        string x4 = root + "/x4" + path;
        if (zoom == 4) return new[] { x4, original };
        return ModX4.Contains(path) ? new[] { x4, native, original } : new[] { native, original, x4 };
    }
